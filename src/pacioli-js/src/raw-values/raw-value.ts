import type { NumericMatrix } from "./numbers";
import { VOID, type PacioliVoid } from "../values/void";
import {
  tableBuilderFromRawMatrix,
  type RawMatrix,
  type RawMatrixStorage,
} from "./raw-matrix";
import { _base_system__adjoin_mut } from "../primitives";
import { PacioliBigNum } from "../values/bignum";
import { MatrixShape } from "../values/matrix-shape";
import { PacioliKind } from "../values/pacioli-value";
import { IndexSet } from "../values/index-set";
import { CustomPacioliValue } from "../values/custom";

/**
 * All possible raw Pacioli values. The unboxed values used by the primitive
 * functions.
 */
export type RawValue =
  | RawMatrix
  | RawList
  | RawSet
  | RawTuple
  | RawArray
  | RawRef
  | RawCoordinates
  | RawFunction
  | RawBoole
  | RawString
  | RawMap
  | RawMaybe
  | RawVoid
  | CustomPacioliValue
  | RawBigNum;

/**
 * Type of an unboxed Pacioli tuple. A javascript array tagged with kind 'tuple'.
 */
export interface RawTuple {
  readonly kind: "tuple";
  readonly items: RawValue[];
}

/**
 * Type of an unboxed Pacioli list. A javascript array tagged with kind 'list'.
 */
export interface RawList {
  readonly kind: "list";
  readonly items: RawValue[];
}
/**
 * Type of an unboxed Pacioli list. A javascript array tagged with kind 'list'.
 */
export interface RawSet {
  readonly kind: "set";
  readonly items: RawValue[];
}

/**
 * Type of an unboxed Pacioli array. A javascript array tagged with kind 'array'.
 */
export interface RawArray {
  readonly kind: "array";
  readonly items: RawValue[];
}

/**
 * Type of raw Void. The same as the non-raw type.
 */
export type RawVoid = PacioliVoid;

/**
 * Type of raw Void. The same as the non-raw type.
 */
export type RawBigNum = PacioliBigNum;

/**
 * Type of an unboxed mutable Pacioli value. A javascript array tagged with kind 'ref'.
 */
export interface RawRef extends Array<RawValue> {
  kind: "ref";
}

export interface RawMaybe {
  readonly kind: "maybe";

  readonly value?: RawValue;
}

export interface RawCoordinates {
  readonly kind: "coordinates";

  readonly position: number;
  readonly size: number;
  readonly names: string[];
  readonly indexSets: IndexSet[];
}

/**
 * Type of the raw (unboxed) Pacioli functions generated by the compiler.
 */
export type RawFunction = (...args: RawValue[]) => RawValue;

/**
 * Type of an unboxed Pacioli string. Maps directly to a javascript string.
 */
export type RawString = string;

/**
 * Type of an unboxed Pacioli boolean. Maps directly to a javascript boolean.
 */
export type RawBoole = boolean;

/**
 * Pacioli's nothing value.
 */

export function makeRawMaybe(value?: RawValue): RawMaybe {
  return { kind: "maybe", value: value };
}

export const NOTHING: RawMaybe = makeRawMaybe(); // { kind: "maybe" };

export function tagMatrix(
  numbers: NumericMatrix,
  nrRows: number,
  nrColumns: number,
  storage: RawMatrixStorage,
  shape: MatrixShape,
): RawMatrix {
  const matrix = numbers as RawMatrix;

  matrix.nrRows = nrRows;
  matrix.nrColumns = nrColumns;
  matrix.storage = storage;
  matrix.kind = "matrix";
  matrix.shape = shape;

  if (shape.nrRows() !== nrRows || shape.nrColumns() !== nrColumns) {
    debugger;
  }

  return matrix;
}

export function tagList(value: RawValue[]): RawList {
  return { kind: "list", items: value };
}

export function tagSet(value: RawValue[]): RawSet {
  let rawSet: RawSet = { kind: "set", items: [] };

  for (const val of value) {
    rawSet = _base_system__adjoin_mut(rawSet, val);
  }

  return rawSet;
}

export function tagTuple(value: RawValue[]): RawTuple {
  return { kind: "tuple", items: value };
}

export function tagArray(value: RawValue[]): RawArray {
  return { kind: "array", items: value };
}

export function tagRef(value: Array<RawValue>): RawRef {
  debugger;
  (value as RawRef).kind = "ref";
  return value as RawRef;
}

/**
 * The RawValue kind is not complete. It is undefined for strings, booleans and functions.
 *
 * This label is an alternative that is complete. Useful to display to the user, etc.
 *
 * @param value Any raw value
 * @returns One of the labels.
 */
export function rawValueLabel(value: RawValue): PacioliKind {
  switch (typeof value) {
    case "string":
      return "string";
    case "boolean":
      return "boole";
    case "function":
      return "function";
    default: {
      return value.kind;
    }
  }
}

/**
 * String representation of a raw Pacioli value.
 *
 * Does not include unit information.
 *
 * Satisfies
 *
 *  x equals y in Pacioli
 *    <=>
 *  stringifyRawValue(x) === stringifyRawValue(y)
 *
 * when units are ignored and equality is defined.
 *
 * The last is important for e.g. boolean true and string
 * "true", but also for list and tuples, because it does
 * not hold in these cases. Function stringifyRawValue
 * treats list and tuples as equal. This is not a problem
 * because Pacioli does not allow equality between a list
 * and a tuple.
 *
 * Is not a method because we use primitive javascript values.
 * For PacioliValue there is the toText method. Where possible
 * we reuse that.
 *
 * @param value
 */
export function stringifyRawValue(value: RawValue): string {
  if (typeof value === "string") {
    return value;
  }

  if (typeof value === "function") {
    return "|closure|";
  }

  if (typeof value === "boolean") {
    return value ? "true" : "false";
  }

  switch (value.kind) {
    case "matrix": {
      return tableBuilderFromRawMatrix(value).ascii();
    }
    case "list": {
      return `[${value.items
        .map((element) => stringifyRawValue(element))
        .join(", ")}]`;
    }
    case "set": {
      return `{${value.items
        .map((element) => stringifyRawValue(element))
        .join(", ")}}`;
    }
    case "tuple": {
      return `(${value.items
        .map((element) => stringifyRawValue(element))
        .join(", ")})`;
    }
    case "array": {
      return `{${value.items
        .map((element) => stringifyRawValue(element))
        .join(", ")}}`;
    }
    case "ref": {
      return `<${value
        .map((element) => stringifyRawValue(element))
        .join(", ")}>`;
    }
    case "coordinates": {
      return `${value.size.toString()}@${value.position.toString()}`;
    }
    case "map": {
      const pairs: string[] = [];

      for (const key of value.keyMap.keys()) {
        const k = value.keyMap.get(key);
        const v = value.valueMap.get(key);
        if (k !== undefined && v !== undefined) {
          pairs.push(`${stringifyRawValue(k)}->${stringifyRawValue(v)}`);
        }
      }
      return `<${pairs.join(", ")}>`;
    }
    case "void": {
      return "Void";
    }
    case "maybe": {
      return value.value === undefined
        ? "Nothing"
        : `just<${stringifyRawValue(value.value)}>`;
    }
    case "custom": {
      return value.stringify();
    }
  }
}

/**
 * Unboxed Pacioli map.
 */
export class RawMap {
  readonly kind = "map";

  valueMap = new Map<string, RawValue>();
  keyMap = new Map<string, RawValue>();

  public store(key: RawValue, value: RawValue): PacioliVoid {
    const effKey = stringifyRawValue(key);
    this.valueMap.set(effKey, value);
    this.keyMap.set(effKey, key);
    return VOID;
  }

  public lookup(key: RawValue): RawMaybe {
    return makeRawMaybe(this.valueMap.get(stringifyRawValue(key)));
  }

  public keys(): RawList {
    const keys: RawValue[] = [];
    for (const key of this.keyMap.values()) {
      keys.push(key);
    }
    return tagList(keys);
  }
}
